CREATE OR REPLACE TABLE team_name_mapping (
    team_name VARCHAR PRIMARY KEY,
    team_code VARCHAR,
    count BIGINT
);

INSERT INTO team_name_mapping (team_name, team_code, count)
SELECT 
    home_team AS team_name,
    home_team_code AS team_code,
    COUNT(*) AS count
FROM xg_df
GROUP BY home_team, home_team_code;

